/**
 * Every tunable number in one place, serialisable, and fed straight to the debug
 * UI. Distances are metres, angles degrees, probabilities [0, 1].
 */

/**
 * Roof colour families. Declared here rather than beside the palettes because
 * the mix between them is a setting, and `material/` already depends on `core/`
 * — the other direction would be a cycle.
 */
export type RoofHue = 'redBrown' | 'navy' | 'grey' | 'brown' | 'green';
export type RoofHueMix = Record<RoofHue, number>;

/**
 * How the street network is laid out. Both are the same generator — Tier-1
 * roads cut the town into districts, each district grids itself — differing
 * only in how much the districts are allowed to disagree with each other.
 *
 * `district` is the default: several districts at visibly different angles,
 * with dead ends and staggered junctions. An organically grown suburb, where
 * each development was fitted to the land it replaced.
 * `grid` is the planned 区画整理 alternative — one dominant orientation,
 * nothing deleted, nothing dead-ending, and a pair of diagonal through-roads.
 */
export type RoadLayout = 'district' | 'grid';

/**
 * Declared here rather than beside the road generator because `perimeterClass`
 * is a setting, and `city/` already depends on `core/` — the other direction
 * would be a cycle. `city/Roads.ts` re-exports it as the canonical name.
 */
export type RoadClass = 'arterial' | 'collector' | 'local' | 'private';

/**
 * 用途地域 — the use zone a *district* is designated as.
 *
 * Declared here for the same reason as `RoadClass`: the mix is a setting, and
 * `city/` already depends on `core/`. Keeping it here also lets `District`
 * carry its own zone without `RoadDistricts` importing the assignment.
 *
 * The distinction this type draws is the one Japanese planning already draws,
 * and the reason it is worth keeping in the type system: **用途地域 is the map**
 * — decided upstream, per district, before a single lot exists — while
 * `LotKind` is **what actually got built**, decided per lot from the geometry
 * the map made possible. A zone never places a building. It only says which
 * ones the geometric gates are allowed to consider.
 */
export type UseZone =
  | 'lowRise' // 第一種低層住居専用地域
  | 'midRise' // 第一種中高層住居専用地域・住居地域
  | 'neighbourCom' // 近隣商業地域
  | 'commercial' // 商業地域（駅前）
  | 'quasiIndust' // 準工業地域
  | 'industrial'; // 工業地域

export interface LandUseParams {
  /** Radius over which the station's pull on 商業地域 falls off, metres. */
  commercialCoreRadius: number;
  /** How far 近隣商業 may reach from the station along a wide road, metres. */
  neighbourhoodRadius: number;
  /**
   * Ceiling on the combined area of 商業 and 近隣商業, as a share of the town.
   *
   * A radius alone does not bound it. The town shrinks but the districts do not
   * shrink with it, so at `extent: 190` the shops reached most of the map and a
   * quarter of every lot came out a 店舗併用住宅. Shops are a share of a town, not
   * a distance from its station.
   */
  commercialShare: number;
  /** Target share of the town area given over to 工業地域, [0, 1]. */
  industrialShare: number;
  /** No industrial district may come closer than this to the station, metres. */
  industrialMinStationDist: number;
  /** Ring 準工業 around the industrial belt, so a factory never abuts 低層住専. */
  quasiIndustrialRing: boolean;
  /** How much Tier-1 frontage counts toward being commercial, relative to the station. */
  arterialFrontageWeight: number;
  noiseScale: number;
  noiseWeight: number;
}

/**
 * The river. One river, running right across the town — deliberately not a pond
 * and deliberately not a tributary network.
 *
 * `geom/boolean.ts` drops holes, and a body of water that closes inside a single
 * block *is* a hole: it would be silently swallowed and a house would be built
 * on it. A river that crosses the town splits every block it touches into two,
 * which the boolean pipeline handles correctly.
 */
export interface RiverParams {
  enabled: boolean;
  /** Width of the water surface, metres. */
  width: number;
  /** How far from the centreline the valley carve reaches. */
  valleyWidth: number;
  /**
   * Minimum downstream fall, as a fraction. The bed profile is forced monotone
   * with at least this gradient: a river that runs uphill is the single most
   * obvious way to break the illusion, and an fBm field will happily produce one
   * if the carve is a plain subtraction.
   */
  bedGrade: number;
  /** Water surface above the bed. */
  waterDepth: number;
  /** Extra width beyond the water that nothing may be built on. */
  bankMargin: number;
  /** Lateral wander of the centreline, metres. */
  meander: number;
}

/**
 * 段丘崖 — the terrace scarps.
 *
 * Generated by offsetting the river centreline sideways, because that is what a
 * 河岸段丘 is: the abandoned floors of the same valley. Terraces placed
 * independently of the river read as random walls.
 */
export interface TerraceParams {
  count: number;
  /** Height of one scarp, metres. */
  step: number;
  stepVariation: number;
  /**
   * Width of the scarp band, metres.
   *
   * Kept at one grid cell. A step of 4 m over a band of 4 m is 45° — unwalkable,
   * undrivable, and it forces a 擁壁 on every lot along it, which is the point.
   * Anything narrower is destroyed by the bilinear sampler anyway, so a narrower
   * band would only be a lie.
   */
  width: number;
  /** Lateral offset from the river, as a fraction of the town half-extent. */
  minOffset: number;
  maxOffset: number;
}

/**
 * The land the town is built on.
 *
 * Everything here is in absolute metres and deliberately *not* scaled by
 * `roads.extent`. The tests run a 190 m town and the shipped one is 320 m; if
 * the hills scaled with the town, the tested landscape would not be the shipped
 * landscape and the suite would stop testing what actually ships.
 */
export interface TerrainParams {
  enabled: boolean;
  /** Heightfield sample pitch, metres. */
  cell: number;
  /** How far the field extends beyond the town square, metres. */
  margin: number;
  /** Peak-to-trough relief of the hills, metres. */
  relief: number;
  hillScale: number;
  hillOctaves: number;
  /**
   * Overall fall across the town, as a fraction. Without it the fBm reads as
   * random lumps rather than as a landform that water could drain off.
   */
  tiltGrade: number;
  /**
   * Ground steeper than this (as a tangent) carries no building.
   *
   * Generous on purpose — 0.8 is nearly 39°. A Japanese hill suburb is built on
   * ground far steeper than anything you could stand a house on unaided, and the
   * whole 造成 machinery in `city/Platform.ts` exists to make that work: the lot
   * is cut to a level pad and the 擁壁 holds the difference. Setting this to
   * something a *natural* slope could carry throws away most of the hillside and
   * leaves the walls with nothing to retain.
   */
  maxBuildSlope: number;
  river: RiverParams;
  terrace: TerraceParams;
}

/**
 * How the town grew.
 *
 * Nested inside `RoadParams` rather than sitting beside it: growth decides where
 * roads go, `ROAD_LAYOUT_PRESETS` has to be able to set it, and `generateRoads`
 * then needs no extra argument.
 */
export interface GrowthParams {
  enabled: boolean;
  /** The town's age. The one control this whole feature exists to expose. */
  steps: number;
  /**
   * The step at which the frontier reaches the edge of the town.
   *
   * This is what makes `steps` a *clock* rather than a second seed. The frontier
   * schedule has to be a function of the absolute step number, not of
   * `step / steps` — with the latter, raising the age changed the radius every
   * step aimed at, so the candidate set differed from step one and the whole
   * network came out unrecognisably different. An older town is supposed to be
   * the younger one with more added to it.
   *
   * A town with `steps` below this is caught mid-growth: smaller, with its
   * frontier still short of the perimeter. Above it, the extra steps go into
   * filling in what is already there.
   */
  fullAt: number;
  /**
   * How the frontier radius grows with step, as an exponent. Below 1 the town
   * spreads fast and then spends its later steps filling the core in — which is
   * what produces the density gradient the whole thing is for.
   */
  spreadExponent: number;
  streetsPerStep: number;
  candidatesPerStreet: number;
  /**
   * Plot size at the station and at the fringe, as a multiple of the zone's own
   * mean. The town's density gradient lives here — see `city/LotModule.ts`,
   * which sizes the street grid to whichever plot a district is getting.
   */
  coreLotScale: number;
  fringeLotScale: number;
  /** Steps between promoting a local chain to collector / a collector to arterial. */
  collectorInterval: number;
  arterialInterval: number;
  /** Steepest longitudinal gradient each class of road will accept, as a tangent. */
  maxGradient: Record<RoadClass, number>;
  maxBridgeSpan: number;
  /** A road may only bridge the river if it crosses it more squarely than this. */
  minRiverCrossAngle: number;
  /** Share of the newest generation's lots left undeveloped. */
  fringeVacancy: number;
  /** Gauss–Seidel sweeps in the road profile solver. Fixed, so it stays deterministic. */
  profileRelaxIterations: number;
  // --- Candidate cost weights ----------------------------------------------
  slopeWeight: number;
  cutFillWeight: number;
  crossSlopeWeight: number;
  spacingWeight: number;
  reachWeight: number;
  loopBonus: number;
  bridgeCost: number;
}

/**
 * 造成 — how a lot is levelled into the slope, and what holds the result up.
 *
 * Its own group rather than part of `buildings`, because none of it is a
 * property of the building: an empty lot on a slope still gets a platform and
 * still needs a wall.
 */
export interface PlatformParams {
  enabled: boolean;
  /** How far the pad sits above the street by default. Japanese lots are raised. */
  plinth: number;
  /**
   * Pad heights snap to a multiple of this — one stair riser.
   *
   * This is what makes a row of pads down a sloping street line up into a
   * staircase instead of a smooth ramp, and it is the whole visual signature of
   * 雛壇造成.
   */
  riserQuantum: number;
  maxRiseAboveStreet: number;
  maxCutBelowStreet: number;
  /** Height difference above which a boundary gets a wall rather than a batter. */
  wallMin: number;
  wallThickness: number;
  /** How far inside the boundary the wall stands. */
  wallInset: number;
  /** Run over rise of an earth batter. */
  batterSlope: number;
  stepRiser: number;
  /** Cut or fill at a road edge above which it is walled rather than battered. */
  roadWallMin: number;
}

export interface RoadParams {
  layout: RoadLayout;
  growth: GrowthParams;
  /** Straight through-roads cutting across the grid. Used by the `grid` layout. */
  diagonalCount: number;
  /** Half-extent of the generated town, metres. */
  extent: number;
  arterialCount: number;
  arterialWidth: number;
  collectorWidth: number;
  collectorSpacing: number;
  localWidth: number;
  /**
   * How much neighbouring blocks differ in *length*, as a fraction.
   *
   * Only along the street. A block's depth is two lot depths and is not
   * negotiable — varying it by ±18%, which is what this number used to do to
   * both axes at once, moved the block between 22 m and 40 m of usable depth
   * where the lots needed 27, and the subdivider then stretched or abandoned the
   * difference. Along the street the same variation is free: it changes how many
   * plots fit and nothing else, and it is what stops a district reading as
   * graph paper.
   */
  gridSpacingVariation: number;
  /** Fraction of street spans deleted outright. */
  deleteFraction: number;
  /** Fraction of terminal spans truncated into dead ends. */
  deadEndFraction: number;
  nodeSnap: number;
  minEdgeLength: number;

  // --- District layout ------------------------------------------------------
  /** One grain for the whole town: how far the base axis tilts off north, degrees. */
  townAxisJitter: number;
  /** Bends per Tier-1 road. A real 幹線道路 has two or three, not ninety. */
  tier1BendCount: number;
  /** Hard cap on a single Tier-1 bend, degrees. */
  tier1MaxBend: number;
  /** Two Tier-1 roads may never come closer than this except where they cross, metres. */
  tier1MinSpacing: number;
  /**
   * Junctions sharper than this are not built. Acute crossings are what produce
   * the overlapping asphalt and the sliver blocks that get discarded, so this
   * is a hard constraint on the skeleton rather than a preference.
   */
  minJunctionAngle: number;
  /** How far a district's grid may rotate off its dominant boundary road, degrees. */
  districtAxisJitter: number;
  /** Faces below this get no local grid and stay a single block, m². */
  minDistrictArea: number;
  /** Floor on a local grid gap, metres. */
  minLocalSpacing: number;
  /** Share of local street lines given a 食い違い offset. */
  staggerFraction: number;
  staggerDistance: number;
  /** Probability a local street bends once, at one of its junctions. */
  localBendChance: number;
  /**
   * Cap on that bend, degrees. The bend sits *on* a junction, so every block
   * edge stays straight and every lot along a run keeps one exact frontage
   * direction — the street reads as bent without the houses fanning out.
   */
  localBendAngle: number;
  /** Gap required between the ribbons of two roads that do not share a node, metres. */
  roadClearance: number;
  /**
   * Close the town square with a road. Effectively mandatory: `extractFaces`
   * discards the single clockwise outer cycle, so without a ring the outermost
   * region is not a face and there are no boundary districts at all.
   */
  perimeterRoad: boolean;
  perimeterClass: RoadClass;
  /** Assign the road hierarchy to the district's own grid lines. */
  promoteGridLines: boolean;
}

export interface LotParams {
  minLotArea: number;
  maxLotArea: number;
  /**
   * Cap for parcels with wide frontage on an arterial or collector. Those
   * parcels are consolidated in reality, and they are the only places a
   * マンション can physically go — so the zoning rules never have to name one.
   */
  maxLotAreaMajor: number;
  /** Lot width and depth are larger along wide roads. */
  widthMeanMajor: number;
  depthMeanMajor: number;
  /**
   * Minimum street frontage, metres. Japan's 接道義務 is 2 m, but this doubles
   * as the acceptance test for leftover scraps, and a suburb is full of parcels
   * that never had to satisfy it — 未接道 slivers between two developments, the
   * corner a road widening left behind. Kept below the legal figure so those
   * survive as ground rather than vanishing.
   */
  minFrontage: number;
  /**
   * Mean and spread of lot depth.
   *
   * The master dimension of the whole town, not a preference. `LotModule` spaces
   * the streets at two of these plus the road between them, so raising it does
   * not make the lots deeper within the same blocks — it makes the blocks
   * deeper. What it changes is the *proportion* of the plot, and through that
   * the proportion of the house: 12.8 against a 9.6 m frontage is a plot half
   * again as deep as it is wide, and a house a little less than that once the
   * setbacks and the parking space are taken off the front.
   */
  depthMean: number;
  depthSigma: number;
  depthMin: number;
  depthMax: number;
  /** Mean and spread of lot width along the street. */
  widthMean: number;
  widthSigma: number;
  widthMin: number;
  widthMax: number;
  /** Non-parallel side boundaries: sigma of the cut-direction jitter, degrees. */
  cutAngleJitter: number;
  /** A block core at least this large can be opened up with a private lane. */
  minCoreArea: number;
  /** A smaller core still supports flag lots reached by a pole. */
  flagLotMinCore: number;
  /** Width of a 私道 (designated private road). */
  privateLaneWidth: number;
  /** Width of a flag lot's pole (竿). */
  poleWidth: number;
  flagLotChance: number;
  /**
   * Parcels whose largest inscribed circle is smaller than this are discarded.
   * This, not `minLotArea`, is what actually rejects a scrap: a 3 m × 4 m corner
   * is 12 m² but only holds a 1.5 m circle. Lowering `minLotArea` without
   * lowering this changes nothing.
   */
  minInscribedRadius: number;
  /** Gutter allowance added to each road's half width. */
  gutterWidth: number;
  maxRecursionDepth: number;
}

