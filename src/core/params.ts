/**
 * Apply a layout preset in place, leaving unrelated road parameters alone.
 *
 * `growth` is merged rather than replaced, for two reasons. A blind
 * `Object.assign` would alias one shared `growth` object across every
 * `cloneParams` result — tuning one town would silently tune all of them. And
 * the town's age is something the user sets and then switches layout under; the
 * preset only has an opinion about whether growth runs at all.
 */
export function applyRoadLayout(roads: RoadParams, layout: RoadLayout): RoadParams {
  const { growth, ...rest } = ROAD_LAYOUT_PRESETS[layout];
  Object.assign(roads, rest, { layout });
  if (growth) Object.assign(roads.growth, growth);
  return roads;
}

export function cloneParams(p: CityParams): CityParams {
  return structuredClone(p);
}

